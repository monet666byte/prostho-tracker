/** "ที่" ที่ป้ายชื่อผู้ป่วยไปโผล่ — ชื่อบอกงานที่คนกำลังทำ ไม่ใช่ชื่อไฟล์ */
export type IdentitySurface =
  /** นักศึกษาดูเคสของตัวเอง (หน้าแรก · คนไข้ · รายละเอียดเคส · ค้นหา · คลังรูป · ส่งออกของตัวเอง) */
  | 'own-case'
  /** อาจารย์ตรวจงานรายเคส — ต้องจับคู่กับแฟ้มคนไข้จริงเพื่อเซ็นรับงาน */
  | 'teacher-case-review'
  /** อาจารย์นำเข้าข้อมูลจากชีต — ต้องเห็นของจริงเพื่อตรวจว่าอ่านถูก */
  | 'sheet-import'
  /** อาจารย์กรอกใบประเมิน Section II/III — ใบนี้เป็นเอกสารของผู้ป่วยรายนั้น พิมพ์ออกไปลงนาม
   *  ชื่อกับ HN เป็นเนื้อหาของใบ ไม่ใช่ของประดับ · ตัวเลือกเคสก็ต้องเป็นของจริง
   *  ไม่งั้นจะกลายเป็น "กดชิปที่เขียนว่า PT-7K2M9 แล้วชื่อจริงโผล่ในช่อง" = ปิดบังแบบหลอกตา */
  | 'case-form'
  /** อาจารย์ให้คะแนนรายคาบ — ให้คะแนน "นักศึกษา" คนไข้เป็นแค่บริบทว่าคาบนั้นทำอะไร */
  | 'session-eval';

export function identityLevelFor(surface: IdentitySurface, maskByDefault: boolean): IdentityLevel {
  if (surface === 'own-case' || surface === 'sheet-import'
    || surface === 'teacher-case-review' || surface === 'case-form') return 'full';
  // ปิดสวิตช์ = กลับไปพฤติกรรมเดิม (เห็นชื่อทุกหน้า) — ให้ภาคเลือกได้ ไม่ใช่บังคับ
  if (!maskByDefault) return 'full';
  /* 'initials' ไม่ใช่ 'code' เพราะอาจารย์ต้องแยก "คาบนี้ทำเคสไหน" ออกจากกันบนหน้าจอเดียว
     รหัสเคสล้วนอ่านยากมากเวลามีหลายแถวติดกัน (PT-7K2M9 vs PT-7K2N4) */
  return 'initials';
}
