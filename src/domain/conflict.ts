import type { Review } from './types';

/**
 * เรียงใบตัดสินใหม่สุดขึ้นก่อน
 * ต้องมีตัวตัดสินสำรอง (id) ด้วย ไม่งั้นสองใบที่เวลาเท่ากันเป๊ะจะสลับที่กันไปมา
 * แล้วสองเครื่องจะเห็นคนละใบ ทั้งที่ข้อมูลชุดเดียวกัน
 */
export const byNewestReview = (a: Review, b: Review) =>
  (b.at ?? '').localeCompare(a.at ?? '') || (b.id ?? '').localeCompare(a.id ?? '');

/**
 * ชิ้นงานหนึ่งชิ้นอาจมีหลายใบตัดสิน (อาจารย์คนละท่านกดคนละเครื่อง ต่างคนต่างสร้าง id)
 * เอาใบล่าสุดเป็นใบที่แสดง ใบที่เหลือไม่ถูกลบ — ใช้ทำป้าย "เคยมีคำตัดสินอื่น"
 *
 * เดิมใช้ `new Map(all.map(...))` ตรงๆ ซึ่งได้ "ใบไหนก็ได้ที่อยู่ท้ายอาร์เรย์"
 * = ลำดับที่ IndexedDB คืนมา ไม่ใช่ใบล่าสุด และไม่เหมือนกันระหว่างเครื่อง
 * อาจารย์สองท่านจึงเห็นคำตัดสินคนละอันของชิ้นงานเดียวกัน โดยไม่มีอะไรบอก
 */
export function pickLatestReviews(all: Review[]): Map<string, Review> {
  const map = new Map<string, Review>();
  for (const r of [...all].sort(byNewestReview)) if (!map.has(r.workpieceId)) map.set(r.workpieceId, r);
  return map;
}

/**
 * ใบประเมิน portfolio ที่กำลังแก้อยู่ เป็นของอาจารย์ท่านอื่นหรือเปล่า
 *
 * Sect2Sheet/Sect3Sheet ตั้งใจให้เครื่องที่สอง "รับแถวที่มีอยู่มาแก้ต่อ"
 * เพื่อไม่ให้มือถือ+iPad ของคนเดียวกันแตกเป็นสองใบ — ถูกสำหรับคนเดียวกัน
 * แต่ผิดเมื่อเป็นคนละคน: อาจารย์สองท่านเปิดใบเดียวกันจะเขียน id เดียวกัน
 * และร่างอัตโนมัติยิงทุกครั้งที่กา (silent: true) = ทับกันรัวๆ ตลอดเวลาที่เปิดค้าง
 * คะแนนพวกนี้เป็นเงื่อนไขจบ จะหายเงียบไม่ได้ → เจอของคนอื่นให้แตกใบใหม่
 */
export const isOthersForm = (prevBy: string | undefined, actor: string) => !!prevBy && prevBy !== actor;
