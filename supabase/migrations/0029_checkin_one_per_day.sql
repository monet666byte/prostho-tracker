-- 0029 — เช็คอินหนึ่งคนหนึ่งวันได้แถวเดียว บังคับที่ฐานข้อมูล
--
--   กติกา "หนึ่งคนต่อหนึ่งวันได้ครั้งเดียว" มีอยู่แล้วในแอป (repo.ts → addCheckIn เติมลงคาบเดิม)
--   แต่แอปมองเห็นแค่ลิ้นชักของเครื่องตัวเอง · นักศึกษาคนเดียวถือสองเครื่อง (มือถือ + ไอแพด)
--   ออฟไลน์ทั้งคู่ แล้วเช็คอินวันเดียวกัน → ได้ id คนละตัว → ขึ้นเซิร์ฟเวอร์เป็นสองแถว
--   อาจารย์เห็นชื่อคนเดียวโผล่สองแถวในหน้าประเมินรายคาบ = งาน "กันประเมินผิดคน" พัง
--   และยิง API ตรงก็สร้างกี่แถวก็ได้
--
--   → unique index (student_id, date) · แถวที่สองถูกปฏิเสธด้วย 23505
--     ฝั่งแอป: แถวที่ถูกปฏิเสธยังอยู่ในเครื่องนั้นครบ และขึ้นรายการ "ส่งขึ้นเซิร์ฟเวอร์ไม่ได้"
--     ในหน้าตั้งค่าพร้อมคำอธิบาย (ไม่หายเงียบ — กติกาเดียวกับการปฏิเสธแบบอื่นใน cloudSync.ts)
--
--   ⚠️ ถ้าบนเซิร์ฟเวอร์มีแถวซ้ำอยู่แล้ว ไฟล์นี้หยุดพร้อมบอกจำนวน — **ไม่ลบให้เอง**
--      คาบที่ซ้ำอาจมีคะแนนของอาจารย์อยู่คนละแถว ต้องให้คนตัดสินว่าเก็บแถวไหน
--      ดูรายการด้วย:
--        select student_id, date, count(*) from checkins group by 1, 2 having count(*) > 1;
--
-- ต้องรัน 0001–0028 มาก่อน · รันซ้ำได้ · รันแล้วให้รัน supabase/security-check.sql ตาม
-- ─────────────────────────────────────────────────────────────────────────────

do $$
declare
  dup int;
begin
  select count(*) into dup from (
    select 1 from checkins group by student_id, date having count(*) > 1
  ) d;
  if dup > 0 then
    raise exception 'มีเช็คอินซ้ำวัน % คู่ (นักศึกษา+วันที่) — ต้องตัดสินก่อนว่าเก็บแถวไหน แล้วค่อยรันไฟล์นี้ใหม่', dup;
  end if;
end $$;

create unique index if not exists checkins_student_date_uidx on checkins (student_id, date);
